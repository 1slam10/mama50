#!/usr/bin/env python3
"""
Builds one personal page per guest family as a flat file:  <slug>.html
GitHub Pages serves it at  https://<site>/<slug>  (no .html needed).

Run:   python3 build_guests.py
       (optional, before it: node og-cards.js  → personal WhatsApp preview images)

Reads  guests.json, js/config.js
Uses   index.html as the template (the root page stays the generic invitation)
Writes <slug>.html for every guest + guest-links.md (links and ready WhatsApp texts)

Only the Python standard library is needed.
"""
import html
import json
import re
import shutil
import sys
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MARKER = "<!-- generated by build_guests.py: edit index.html / guests.json, not this file -->"
RESERVED = {"index", "make-link", "404", "css", "js", "img", "fonts", "audio"}
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


# ---------- Kazakh helpers (same rules as js/app.js) ----------
def conj_after(word: str) -> str:
    w = re.sub(r"[^a-zа-яёәғқңөұүһі]", "", word.lower())
    w = re.sub(r"[ьъ]+$", "", w)
    last = w[-1:]
    if not last or re.match(r"[a-z]", last):
        return "және"
    if last in "аәеёиоөұүыіэюяулрймнң":
        return "мен"
    if last in "жз":
        return "бен"
    return "пен"


def genitive(word: str) -> str:
    """Мира → Мираның, Әсел → Әселдің, Гүлнар → Гүлнардың (ілік септік)."""
    w = word.strip()
    low = w.lower()
    last = low[-1:]
    vowels = [ch for ch in low if ch in "аәеёиоөұүыіэюяу"]
    front = bool(vowels) and vowels[-1] in "әеөүіэи"
    if last in "аәеёоөұүыіэюя" or last in "мнң":
        suf = "нің" if front else "ның"
    elif last in "лрйузжи":
        suf = "дің" if front else "дың"
    else:
        suf = "тің" if front else "тың"
    return w + suf


def read_config():
    cfg = (ROOT / "js" / "config.js").read_text(encoding="utf-8")
    name = re.search(r'mom:\s*\{[^}]*?name:\s*"([^"]*)"', cfg, re.S)
    age = re.search(r'age:\s*(\d+)', cfg)
    return (name.group(1) if name else ""), (int(age.group(1)) if age else 50)


def join_kz(names):
    if not names:
        return ""
    if len(names) == 1:
        return names[0]
    if len(names) == 2:
        return f"{names[0]} {conj_after(names[0])} {names[1]}"
    return ", ".join(names[:-1]) + " және " + names[-1]


TRANSLIT = {
    "а": "a", "ә": "a", "б": "b", "в": "v", "г": "g", "ғ": "g", "д": "d", "е": "e", "ё": "yo",
    "ж": "zh", "з": "z", "и": "i", "й": "i", "к": "k", "қ": "k", "л": "l", "м": "m", "н": "n",
    "ң": "n", "о": "o", "ө": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ұ": "u",
    "ү": "u", "ф": "f", "х": "kh", "һ": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sh",
    "ъ": "", "ы": "y", "і": "i", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def auto_slug(names):
    s = "-".join(n.split()[0] for n in names).lower()          # first word of each name, honorifics dropped
    s = "".join(TRANSLIT.get(ch, ch) for ch in s)
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")


# ---------- build ----------
def set_meta(page, attr, key, value):
    pattern = re.compile(rf'<meta {attr}="{re.escape(key)}" content="[^"]*">')
    tag = f'<meta {attr}="{key}" content="{html.escape(value, quote=True)}">'
    if pattern.search(page):
        return pattern.sub(lambda _: tag, page, count=1)
    return page.replace("</title>", "</title>\n  " + tag, 1)


def set_share_tags(page, title, description, url, image, alt):
    """Everything WhatsApp / Telegram / iMessage read to draw the preview card."""
    for attr, key, val in [
        ("property", "og:title", title), ("property", "og:description", description),
        ("property", "og:url", url), ("property", "og:image", image),
        ("property", "og:image:secure_url", image), ("property", "og:image:alt", alt),
        ("name", "twitter:title", title), ("name", "twitter:description", description),
        ("name", "twitter:image", image), ("name", "description", description),
    ]:
        page = set_meta(page, attr, key, val)
    return page


def main():
    data = json.loads((ROOT / "guests.json").read_text(encoding="utf-8"))
    site = data["siteUrl"].rstrip("/")
    share_line = data.get("shareLine", "")
    mom, age = read_config()
    invite_title = (f"{genitive(mom)} " if mom else "") + f"{age} жасқа толу мерекесіне шақыру"
    template_path = ROOT / "index.html"
    template = template_path.read_text(encoding="utf-8")

    # root page (generic invitation): absolute URLs, WhatsApp needs them
    root_page = set_share_tags(template, invite_title[0].upper() + invite_title[1:], share_line,
                               f"{site}/", f"{site}/img/og.jpg", invite_title)
    if root_page != template:
        template_path.write_text(root_page, encoding="utf-8")
        template = root_page

    seen, errors, rows = set(), [], []
    for g in data["guests"]:
        names = [n.strip() for n in g.get("names", []) if n.strip()]
        kids = [n.strip() for n in g.get("kids", []) if n.strip()]
        slug = g.get("slug") or auto_slug(names + kids)
        if not names:
            errors.append(f"{slug}: no names"); continue
        if not SLUG_RE.match(slug) or slug in RESERVED:
            errors.append(f"{slug}: bad slug (use a-z, 0-9 and hyphens)"); continue
        if slug in seen:
            errors.append(f"{slug}: duplicate slug"); continue
        if len(names) > 5:
            errors.append(f"{slug}: max 5 names in 'names' (put children in 'kids')"); continue
        seen.add(slug)

        plural = bool(g.get("plural")) or len(names) + len(kids) != 1
        lead = join_kz(names)
        everyone = join_kz(names + kids)

        url = f"{site}/{slug}"
        card = f"img/og/{slug}.jpg" if (ROOT / "img" / "og" / f"{slug}.jpg").exists() else "img/og.jpg"

        page = template.replace("<!doctype html>", "<!doctype html>\n" + MARKER, 1)
        page = page.replace('<meta name="viewport"', '<meta name="robots" content="noindex, nofollow">\n  <meta name="viewport"', 1)
        page = re.sub(r"<title>.*?</title>", lambda _: f"<title>{html.escape(lead)} · Туған күнге шақыру</title>", page, count=1)
        page = set_share_tags(page, f"Қымбатты {everyone}!", f"{invite_title} · {share_line}".strip(" ·"),
                              url, f"{site}/{card}", f"Қымбатты {everyone}! {invite_title}")
        guest_js = json.dumps({"names": names, "kids": kids, "plural": plural}, ensure_ascii=False)
        page = page.replace('<script src="js/config.js" defer></script>',
                            f'<script>window.GUEST = {guest_js};</script>\n  <script src="js/config.js" defer></script>', 1)
        (ROOT / f"{slug}.html").write_text(page, encoding="utf-8")

        msg = f"Қымбатты {everyone}! {invite_title[0].upper() + invite_title[1:]}: {share_line}.\n{url}"
        rows.append((slug, everyone, url, msg))

    # remove pages of guests that were deleted from guests.json
    for f in ROOT.glob("*.html"):
        if f.stem not in seen and MARKER in f.read_text(encoding="utf-8")[:400]:
            f.unlink()
            print(f"removed stale page: {f.name}")

    # links list for the hosts
    lines = ["# Шақыру сілтемелері", "",
             "Tap a WhatsApp link → choose the chat → send. The text and the link are already filled in.", ""]
    for i, (slug, everyone, url, msg) in enumerate(rows, 1):
        wa = "https://wa.me/?text=" + urllib.parse.quote(msg)
        lines += [f"## {i}. {everyone}", f"- Page: {url}", f"- [Send via WhatsApp]({wa})", "", "```", msg, "```", ""]
    (ROOT / "guest-links.md").write_text("\n".join(lines), encoding="utf-8")

    for slug, everyone, url, _ in rows:
        print(f"{url:50s} {everyone}")
    if errors:
        print("\nERRORS:\n  " + "\n  ".join(errors))
        sys.exit(1)
    print(f"\n{len(rows)} pages built. Links + WhatsApp texts: guest-links.md")


if __name__ == "__main__":
    main()
